import pandas as pd

def create_new_features(df):
    df_new = df.copy()

    # 1. Agresif Sürüş İndeksi
    df_new['aggressive_driving_index'] = df_new['harsh_braking_count'] * df_new['rpm_variation']

    # 2. Dur-Kalk Trafik Etkileşimi
    df_new['idle_braking_interaction'] = df_new['idling_time'] * df_new['harsh_braking_count']

    # 3. Sürüş Akıcılık Göstergesi
    # Sıfıra bölünme hatasını önlemek için paydaya 1 ekliyoruz
    df_new['driving_smoothness_indicator'] = df_new['acceleration_smoothness'] / (df_new['harsh_braking_count'] + 1)

    # 4. Motor Zorlanma Oranı
    # Paydaya 0.001 ekleyerek sıfıra bölünmeyi engelliyoruz
    df_new['rpm_smoothness_ratio'] = df_new['rpm_variation'] / (df_new['acceleration_smoothness'] + 0.001)

    # 5. Sert Fren Cezası
    df_new['harsh_driving_penalty'] = df_new['harsh_braking_count'] ** 2

    return df_new